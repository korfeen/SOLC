// The Dream Bed's painted pieces (tools/gen-dreambed-art.js: %USERPROFILE%\killtracker-art-extra\DreamBed\pieces) into
// the game: Media\DreamBed\<name>.blp, and DreamBedArt.lua with what the scene needs to place them:
//   ns.DreamBedArt = { room = { w, h, window = { x, y, w, h }, floor }, floor = { w, h }, pieces = { [name] = { box = { x, y, w, h } } },
//     easelCanvas = { x, y, w, h }, layout = tools/dreambed-layout.json }
// box: the piece's visible part in its square (fractions), window: the room's see-through glass, room.floor: where its
// painted wall ends (the rest cut out: floor.blp shows through), layout: where the pieces go (tools/dreambed-room.js),
// easelCanvas: the blank canvas inside the easel's box (where the painting goes). The room is stored 1024x512 (its 3:2
// painting squashed; the scene shows it at the page's shape, cropping its sides a little).
// Usage: node tools/convert-dreambed.js   (restart WoW after: new textures)
const fs = require("fs");
const os = require("os");
const path = require("path");
const { decodePng, resample, writeBlp } = require("./convert-art");

const SRC = path.join(os.homedir(), "killtracker-art-extra", "DreamBed", "pieces");
const OUT = path.join(__dirname, "..", "Media", "DreamBed");
fs.mkdirSync(OUT, { recursive: true });
const art = { pieces: {} };
const r4 = (v) => Math.round(v * 10000) / 10000;

function Box(img, test) {
  let x0 = img.width, y0 = img.height, x1 = -1, y1 = -1;
  for (let y = 0; y < img.height; y++) for (let x = 0; x < img.width; x++) {
    if (test(img.rgba, (y * img.width + x) * 4)) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
  }
  if (x1 < 0) return null;
  return { x: r4(x0 / img.width), y: r4(y0 / img.height), w: r4((x1 - x0 + 1) / img.width), h: r4((y1 - y0 + 1) / img.height) };
}

// The room: its window (see-through, in the wall's upper part; the floor's cut out too) measured; stored 1024x512.
// The floor behind it the same (a wide picture, changeable: other floors later).
const WIDE = new Set(["room.png", "floor.png"]);
{
  const img = decodePng(path.join(SRC, "room.png")), top = Math.floor(img.height * 0.55) * img.width * 4;
  art.room = { w: img.width, h: img.height, window: Box(img, (p, i) => i < top && p[i + 3] < 128) };
  // (where its painted wall ends: the first row see-through across the page - the game stretches the panel below it)
  let y = Math.floor(img.height * 0.4);
  for (; y < img.height; y++) {
    let clear = true;
    for (let k = 1; k < 10; k++) if (img.rgba[(y * img.width + Math.floor(img.width * k / 10)) * 4 + 3] > 20) clear = false;
    if (clear) break;
  }
  art.room.floor = r4(y / img.height);
  writeBlp(path.join(OUT, "room.blp"), 1024, 512, Buffer.from(resample(img, 0, 0, img.width, img.height, 1024, 512)));
}
if (fs.existsSync(path.join(SRC, "floor.png"))) {
  const img = decodePng(path.join(SRC, "floor.png"));
  art.floor = { w: img.width, h: img.height };
  writeBlp(path.join(OUT, "floor.blp"), 1024, 512, Buffer.from(resample(img, 0, 0, img.width, img.height, 1024, 512)));
}
// The pieces: 512 squares (256 for the small ones), their visible box measured.
const SMALL = new Set(["rug", "brush", "pencils", "crayon", "flame", "candle", "mug", "book", "jar"]);
for (const f of fs.readdirSync(SRC).filter((f) => f.endsWith(".png") && !WIDE.has(f))) {
  const name = f.slice(0, -4), img = decodePng(path.join(SRC, f)), size = SMALL.has(name) ? 256 : 512;
  art.pieces[name] = { box: Box(img, (p, i) => p[i + 3] > 40) };
  writeBlp(path.join(OUT, name + ".blp"), size, size, Buffer.from(resample(img, 0, 0, img.width, img.height, size, size)));
  if (name === "easel") {  // (the blank canvas: the big cream area, inside the easel's box)
    const box = art.pieces.easel.box;
    const cream = Box(img, (p, i) => p[i + 3] > 200 && p[i] > 215 && p[i + 1] > 200 && p[i + 2] > 165 && p[i] - p[i + 2] < 60);
    art.easelCanvas = cream && { x: r4((cream.x - box.x) / box.w), y: r4((cream.y - box.y) / box.h), w: r4(cream.w / box.w), h: r4(cream.h / box.h) };
  }
}
// The room laid out by hand (tools/dreambed-room.js): where each piece goes, as fractions of the page.
art.layout = JSON.parse(fs.readFileSync(path.join(__dirname, "dreambed-layout.json"), "utf8"));
const lua = (v) => Array.isArray(v) ? "{ " + v.map(lua).join(", ") + " }"
  : v && typeof v === "object" ? "{ " + Object.keys(v).sort().map((k) => (/^[A-Za-z_]\w*$/.test(k) ? k : `["${k}"]`) + " = " + lua(v[k])).join(", ") + " }"
  : typeof v === "number" ? String(v) : `"${v}"`;
fs.writeFileSync(path.join(__dirname, "..", "DreamBedArt.lua"), ["-- The Dream Bed's painted pieces: where their visible parts are (generated by tools/convert-dreambed.js - don't edit).",
  "local _, ns = ...", "ns.DreamBedArt = " + lua(art), ""].join("\n"));
console.log(`Media/DreamBed: room + ${Object.keys(art.pieces).length} pieces; window ${JSON.stringify(art.room.window)}; easel canvas ${JSON.stringify(art.easelCanvas)}`);
