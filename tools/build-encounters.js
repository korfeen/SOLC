// Writes ../Encounters.lua: every dungeon and raid boss encounter (WoW Forever's DungeonEncounter table) with the
// creature(s) it kills, so a boss fight that ends in a win counts as a kill of each (Guild.lua) even inside
// instances, where the mobs' IDs are secret. Source: references/encounters.csv (encounterID, name, map, npcIDs:
// space-separated, npcNames: |-separated), made by tools/match-encounters.js from the encounters' names and Questie's
// WoW Forever NPC data, with hand-made entries for encounters with several bosses. Encounters missing from it (new
// WoW Forever bosses no creature data knows yet) still count, under the encounter (Guild.lua).
// Usage: node tools/build-encounters.js   No dependencies.

const fs = require("fs");
const path = require("path");

const CSV = path.join(__dirname, "..", "references", "encounters.csv");
const OUT = path.join(__dirname, "..", "Encounters.lua");

// One CSV line: fields, quoted ones may hold commas and "" for a quote.
function fields(line) {
  const out = [];
  let cur = "", quoted = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (quoted && c === '"' && line[i + 1] === '"') { cur += '"'; i++; }
    else if (c === '"') quoted = !quoted;
    else if (c === "," && !quoted) { out.push(cur); cur = ""; }
    else cur += c;
  }
  out.push(cur);
  return out;
}

const rows = fs.readFileSync(CSV, "utf8").trim().split(/\r?\n/).slice(1).map(fields)
  .map(([id, name, , npcs, names]) => ({ id: +id, name, npcs: npcs.trim().split(/\s+/).map(Number), names: (names || "").split("|") }))
  .sort((a, b) => a.id - b.id);
const lua = [
  "-- Generated by tools/build-encounters.js - don't edit; change references/encounters.csv and rerun it.",
  "-- [encounterID] = { { npcID, name }, ... }: the boss creature(s) a dungeon or raid encounter kills.",
  "",
  "local _, ns = ...",
  "",
  "ns.EncounterNPCs = {",
  ...rows.map((r) => `    [${r.id}] = { ${r.npcs.map((n, i) => `{ ${n}, ${JSON.stringify(r.names[i] || r.name)} }`).join(", ")} },`),
  "}",
  "",
];
fs.writeFileSync(OUT, lua.join("\n"));
console.log(`Encounters.lua: ${rows.length} encounters`);
