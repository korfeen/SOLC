// The profile card's icon styles for the game: every icon made in a style (crayon: tools/make-crayon-icons.js; painted:
// tools/gen-icons.js and its --variant tiles) to Media/IconStyles/<style>/<Kind>_<NAME>.blp (128x128, as the
// card's icons), and IconStyles.lua: ns.ICON_STYLES = { { id, name, has = { [icon] = true } } } for the header's edit
// mode (ProfileHeader.lua), where a style is tried on; icons a style hasn't got yet stay the usual ones.
// Usage: node tools/convert-icon-styles.js   (restart WoW after: new textures)
const fs = require("fs");
const os = require("os");
const path = require("path");
const { decodePng, resample, writeBlp } = require("./convert-art");

const ICONS = path.join(os.homedir(), "killtracker-art-extra", "Unlocks", "generated", "icons");
const TARGET = path.join(__dirname, "..", "Media", "IconStyles");  // (not in Media/Overview: convert-overview.js clears that)
const N = 128;
const TILE_NAMES = { white: "white", lightwood: "light oak", darkwood: "dark walnut", parchment: "parchment", stone: "stone", gold: "gilded gold", epic: "epic purple", molten: "molten obsidian",
  ebony: "ebony", iron: "dark iron", slate: "slate", leather: "dark leather", forest: "forest green", wine: "burgundy", midnight: "midnight blue", bronze: "aged bronze" };
const ORDER = ["white", "parchment", "lightwood", "stone", "darkwood", "ebony", "iron", "slate", "leather", "forest", "wine", "midnight", "bronze", "gold", "epic", "molten"];
const styles = {};  // id -> { name, files: { icon: png } }
const add = (id, name, icon, file) => { (styles[id] ||= { name, files: {} }).files[icon] = file; };
const pngs = (dir) => (fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".png") && !f.includes("review")) : []);
for (const f of pngs(path.join(ICONS, "crayon"))) { const [tile, ...rest] = f.slice(0, -4).split("_"); add("crayon_" + tile, "Crayon, " + (TILE_NAMES[tile] || tile), rest.join("_"), path.join(ICONS, "crayon", f)); }
// (painted: the matched set from tools/gen-icon-parts.js, every icon of a style on the same base)
for (const f of pngs(path.join(ICONS, "v2"))) { const [tile, ...rest] = f.slice(0, -4).split("_"); if (TILE_NAMES[tile]) add("painted_" + tile, "Painted, " + TILE_NAMES[tile], rest.join("_"), path.join(ICONS, "v2", f)); }

fs.rmSync(TARGET, { recursive: true, force: true });
let n = 0;
const ids = Object.keys(styles).sort((a, b) => (a.split("_")[0] === b.split("_")[0] ? ORDER.indexOf(a.split("_")[1]) - ORDER.indexOf(b.split("_")[1]) : a < b ? -1 : 1));
for (const id of ids) for (const [icon, file] of Object.entries(styles[id].files)) {
  const img = decodePng(file);
  const out = path.join(TARGET, id, icon + ".blp");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  writeBlp(out, N, N, Buffer.from(resample(img, 0, 0, img.width, img.height, N, N)));
  n++;
}
const lua = ["-- The profile card's icon styles (generated by tools/convert-icon-styles.js - don't edit): tried on in the header's", "-- edit mode; an icon a style hasn't got stays the usual one.", "local _, ns = ...", "ns.ICON_STYLES = {"];
for (const id of ids) lua.push(`    { id = "${id}", name = "${styles[id].name}", has = { ${Object.keys(styles[id].files).sort().map((k) => k + " = true").join(", ")} } },`);
lua.push("}", "");
fs.writeFileSync(path.join(__dirname, "..", "IconStyles.lua"), lua.join("\n"));
console.log(`${ids.length} styles, ${n} icons -> Media/IconStyles, IconStyles.lua`);
