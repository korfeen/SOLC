// The buttons: a square of boards with a painted icon (Media/Icons) on it; x, y = top-left, w x h.
// A "Plank" is drawn in three parts (Media/Wood/PlankLeft, Plank, PlankRight; tools/convert-wood.js): the ends,
// with their nails, keep their shape at PLANK_END times the plank's thickness wide; the middle stretches.
const PLANK_END = 0.645;
// Runes on a button: the sidebar planks' rune (Media/Wood/Rune), one at each side, this share of its height tall.
const RUNE_HEIGHT = 0.6;
const BUTTONS = {
  settings: { x: 818, y: 4, w: 53, h: 50, icon: "Settings", iconSize: 26, runes: true },
  close: { x: 870, y: -4, w: 76, h: 60, icon: "Close", iconSize: 48 },
};

