// The wooden header along the top of the main window: where each plank and the two square buttons go. Writes
// HeaderLayout.lua (read by UI.lua) and a preview of the window's top with the real logo and textures
// (%USERPROFILE%\killtracker-art-extra\Wood\header-preview.png), so the layout can be tuned without the game.
// Coordinates: pixels from the window's top-left corner, y downwards (the window is 950 wide). Planks: centre
// (x, y), length w, thickness h, tilt in degrees (clockwise), texture; drawn in this order, later ones on top.
// Usage: node tools/header-layout.js   (after node tools/convert-wood.js and tools/make-role-icons.js)

