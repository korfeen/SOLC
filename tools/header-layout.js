const MEDIA = path.join(__dirname, "..", "Media");
const LEFT = -30, TOP = -116, W = WIDTH - LEFT + 30, H = 230;
const out = new Float32Array(W * H * 3);
const put = (x, y, rgb, a) => {
  if (x < 0 || y < 0 || x >= W || y >= H || a <= 0) return;
  const i = (y * W + x) * 3;
  for (let k = 0; k < 3; k++) out[i + k] = rgb[k] * a + out[i + k] * (1 - a);
};
// Background, then the window (dark) with the menu column and page area outlines.
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) put(x, y, [32, 32, 34], 1);
for (let y = 0 - TOP; y < H; y++) for (let x = 0 - LEFT; x < WIDTH - LEFT; x++) put(x, y, [18, 18, 20], 1);
for (const [x0, x1] of [[14, 164], [172, WIDTH - 14]]) {
  for (let y = 44 - TOP; y < H; y++) for (let x = x0 - LEFT; x < x1 - LEFT; x++) put(x, y, [10, 10, 12], 1);
}
const sample = (img, u, v) => {
  const x = Math.min(img.width - 1, Math.max(0, u * img.width - 0.5)), y = Math.min(img.height - 1, Math.max(0, v * img.height - 0.5));
  const x0 = Math.floor(x), y0 = Math.floor(y), x1 = Math.min(x0 + 1, img.width - 1), y1 = Math.min(y0 + 1, img.height - 1);
  const fx = x - x0, fy = y - y0, px = (xx, yy, c) => img.rgba[(yy * img.width + xx) * 4 + c];
  return [0, 1, 2, 3].map((c) => (px(x0, y0, c) * (1 - fx) + px(x1, y0, c) * fx) * (1 - fy) + (px(x0, y1, c) * (1 - fx) + px(x1, y1, c) * fx) * fy);
};
// An image drawn into the rectangle centred on (cx, cy), w x h, turned by tilt degrees.
function draw(img, cx, cy, w, h, tilt = 0, shade = 1, tint = [1, 1, 1]) {
  const a = (tilt * Math.PI) / 180, cos = Math.cos(a), sin = Math.sin(a);
  const reach = Math.ceil(Math.hypot(w, h) / 2) + 1;
  for (let y = Math.floor(cy - reach); y <= cy + reach; y++) {
    for (let x = Math.floor(cx - reach); x <= cx + reach; x++) {
      const dx = x + 0.5 - cx, dy = y + 0.5 - cy;
      const lx = dx * cos + dy * sin, ly = -dx * sin + dy * cos;  // into the unturned rectangle
      const u = lx / w + 0.5, v = ly / h + 0.5;
      if (u < 0 || u > 1 || v < 0 || v > 1) continue;
      const [r, g, b, alpha] = sample(img, u, v);
      put(x - LEFT, y - TOP, [r * shade * tint[0], g * shade * tint[1], b * shade * tint[2]], alpha / 255);
    }
  }
}
const textures = {};
const texture = (file) => (textures[file] ??= readBlp(path.join(MEDIA, file + ".blp")));
// A plank in its three parts, along its tilted line (as UI.lua draws it).
function drawPlank(p) {
  const shade = p.shade ?? 1;
  if (p.texture !== "Plank") return draw(texture("Wood/" + p.texture), p.x, p.y, p.w, p.h, p.tilt, shade);
  const end = Math.min(p.h * PLANK_END, p.w / 2 - 1), a = (p.tilt * Math.PI) / 180;
  const along = (d) => [p.x + Math.cos(a) * d, p.y + Math.sin(a) * d];
  draw(texture("Wood/Plank"), p.x, p.y, p.w - 2 * end + 2, p.h, p.tilt, shade);
  draw(texture("Wood/PlankLeft"), ...along(-(p.w - end) / 2), end, p.h, p.tilt, shade);
  draw(texture("Wood/PlankRight"), ...along((p.w - end) / 2), end, p.h, p.tilt, shade);
}
for (const p of PLANKS) drawPlank(p);
for (const b of Object.values(BUTTONS)) {
  draw(texture("Wood/Square"), b.x + b.w / 2, b.y + b.h / 2, b.w, b.h);
  draw(texture("Icons/" + b.icon), b.x + b.w / 2, b.y + b.h / 2, b.iconSize, b.iconSize);
  if (b.runes) {
    const rh = b.h * RUNE_HEIGHT, rw = rh / 2;
    for (const x of [b.x + 3 + rw / 2, b.x + b.w - 3 - rw / 2]) draw(texture("Wood/Rune"), x, b.y + b.h / 2, rw, rh, 0, 1, [0.22, 0.36, 0.78]);
  }
}
// The logo on top, where UI.lua puts it: 210 square, its top-left 21 left of and 110 above the window's.
draw(texture("Logo"), -21 + 105, -110 + 105, 210, 210);

const raw = Buffer.alloc((W * 3 + 1) * H);
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) for (let k = 0; k < 3; k++) {
  raw[y * (W * 3 + 1) + 1 + x * 3 + k] = Math.round(Math.min(255, out[(y * W + x) * 3 + k]));
}
const crcTable = Array.from({ length: 256 }, (_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c >>> 0; });
const crc = (b) => { let c = 0xffffffff; for (const v of b) c = crcTable[(c ^ v) & 255] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
const chunk = (type, data) => { const l = Buffer.alloc(4); l.writeUInt32BE(data.length); const td = Buffer.concat([Buffer.from(type), data]); const c = Buffer.alloc(4); c.writeUInt32BE(crc(td)); return Buffer.concat([l, td, c]); };
const header = Buffer.alloc(13); header.writeUInt32BE(W, 0); header.writeUInt32BE(H, 4); header[8] = 8; header[9] = 2;
const preview = path.join(os.homedir(), "killtracker-art-extra", "Wood", "header-preview.png");
fs.writeFileSync(preview, Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk("IHDR", header),
  chunk("IDAT", zlib.deflateSync(raw)), chunk("IEND", Buffer.alloc(0))]));
console.log(`Wrote HeaderLayout.lua and ${preview}`);
